// Embeds selected D1 migrations into the Worker (src/schema/migrations.gen.ts) so the owner can apply them from
// the API (POST /api/admin/migrations/apply) or the cron when `wrangler d1 migrations apply --remote` is not available.
// Only additive, idempotent migrations (CREATE ... IF NOT EXISTS) belong here. Run: node scripts/embed-migrations.mjs
import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("../apps/api/migrations/", import.meta.url);
const names = ["0004_forge.sql", "0005_discovery.sql", "0006_redteam.sql", "0007_memory_court.sql", "0008_studio_services.sql", "0009_army.sql", "0010_service_redteam.sql"];
const items = names.map((name) => {
  const sql = readFileSync(new URL(name, dir), "utf8");
  const statements = sql
    .split("\n")
    .map((l) => l.replace(/--.*$/, ""))
    .join("\n")
    .split(";")
    .map((s) => s.replace(/\s+/g, " ").trim())
    .filter(Boolean);
  for (const s of statements) if (!/^CREATE (UNIQUE |VIRTUAL )?(TABLE|INDEX) IF NOT EXISTS /i.test(s)) throw new Error(`${name}: non-idempotent statement: ${s.slice(0, 80)}`);
  return { name, statements };
});
writeFileSync(
  new URL("../apps/api/src/schema/migrations.gen.ts", import.meta.url),
  `// GENERATED by scripts/embed-migrations.mjs — do not edit. Source: apps/api/migrations/${names.join(", ")}\nexport const EMBEDDED_MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(items, null, 1)};\n`,
);
console.log(items.map((i) => `${i.name}: ${i.statements.length} statements`).join("\n"));
