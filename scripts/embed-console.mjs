#!/usr/bin/env node
// Embeds apps/console/public into apps/api/src/embedded-assets.gen.ts so the Worker can serve the console
// without Workers Static Assets (whose upload JWT gets clobbered by Hark's auth-injecting proxy).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "apps/console/public");
const types = { html: "text/html; charset=utf-8", js: "text/javascript; charset=utf-8", css: "text/css; charset=utf-8", svg: "image/svg+xml", json: "application/json" };
const files = {};
for (const f of readdirSync(dir)) {
  if (f === "_headers") continue;
  const ext = f.split(".").pop();
  files["/" + f] = { type: types[ext] ?? "application/octet-stream", body: readFileSync(join(dir, f), "utf8") };
}
// Cache-bust: index.html references each local .js/.css with ?v=<content hash>, so a deploy never mixes
// a fresh index.html with edge/browser-cached old scripts (they are served with max-age).
if (files["/index.html"]) {
  files["/index.html"].body = files["/index.html"].body.replace(/(src|href)="([\w.-]+\.(?:js|css))(?:\?v=[\w]+)?"/g, (m, attr, f) =>
    files["/" + f] ? `${attr}="${f}?v=${createHash("sha256").update(files["/" + f].body).digest("hex").slice(0, 10)}"` : m);
}
writeFileSync(join(root, "apps/api/src/embedded-assets.gen.ts"), "// GENERATED by scripts/embed-console.mjs — do not edit\nexport const FILES: Record<string, { type: string; body: string }> = " + JSON.stringify(files) + ";\n");
console.log("embedded", Object.keys(files).length, "console files");
